  const listeners = [];

  function t(key, vars) {
    let s = (S[lang] && S[lang][key]) || S.en[key] || key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : vars[k]));
    return s;
  }

  function apply() {
    document.documentElement.lang = lang;
    const dict = S[lang] || {};
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      if (!original.has(el)) original.set(el, el.innerHTML);
      const v = lang === 'en' ? null : dict[el.dataset.i18n];
      el.innerHTML = v != null ? v : original.get(el);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      if (el.dataset.phEn == null) el.dataset.phEn = el.getAttribute('placeholder') || '';
      const v = lang === 'en' ? null : dict[el.dataset.i18nPh];
      el.setAttribute('placeholder', v != null ? v : el.dataset.phEn);
    });
    if (originalTitle == null) originalTitle = document.title;
    document.title = lang === 'en' ? originalTitle : dict['meta.title'] || originalTitle;
    const desc = document.querySelector('meta[name="description"]');
    if (desc) {
      if (originalDesc == null) originalDesc = desc.content;
      desc.content = lang === 'en' ? originalDesc : dict['meta.desc'] || originalDesc;
    }
    document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  }

  function set(l) {
    if (!LANGS[l] || l === lang) return;
    lang = l;
    try {
      localStorage.setItem(STORE, l);
    } catch (e) {}
    apply();
    listeners.forEach((fn) => fn(l));
  }

  function data(kind, id) {
    return (D[lang] && D[lang][kind] && D[lang][kind][id]) || {};
  }

  document.addEventListener('click', (e) => {
    const b = e.target.closest('[data-lang]');
    if (b) set(b.dataset.lang);
  });

  apply();

